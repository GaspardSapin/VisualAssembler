//! Hot-exit backups (m4-editor-shell.md §4.8, frozen): `<data>/backups/<id>.txt` holds the
//! UTF-8 text of one unsaved buffer and `<data>/backups/index.toml` lists them.
//!
//! Order is the whole safety argument. [`BackupStore::write`] writes `<id>.txt` atomically,
//! then the index atomically; [`BackupStore::remove`] writes the index first, then deletes the
//! text. A kill at any point therefore leaves a complete earlier state, or an orphan `<id>.txt`
//! that [`BackupStore::open`] adopts, never an index entry pointing at a torn file. Only names
//! `b<16 hex>.txt` are read, so a temp file left by a kill is never mistaken for a backup.
//!
//! An index with a newer `schema_version` is never rewritten: the store is then disabled for
//! the session and every write or removal is refused.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::SystemTime;

use toml::{Table, Value};

use super::atomic::{
    DiskStamp, WriteFn, millis_to_system_time, read_limited, system_time_to_millis, write_atomic,
};
use super::session::{Session, TabSource, toml_string};
