/// The only index `schema_version` this build reads and writes.
const SCHEMA_VERSION: i64 = 1;

/// Largest backup text read, in bytes: the largest document (`va_core` source limit, 16 MiB).
const MAX_TEXT_BYTES: usize = va_core::source::MAX_SOURCE_BYTES;

/// Largest index read, in bytes (an app-read file, capped like the configuration files).
const MAX_INDEX_BYTES: usize = MAX_CONFIG_BYTES;

/// Number of hex digits after the `b` of a backup id.
const ID_DIGITS: usize = 16;

/// Extension of a backup text file.
const TEXT_EXTENSION: &str = ".txt";

/// The encoding recorded when an index entry has none.
const DEFAULT_ENCODING: &str = "utf-8";

/// Bits of a generated id that hold the counter; the time in milliseconds fills the rest.
const COUNTER_BITS: u32 = 16;

/// The largest id value generated or seen by this process; the next generated one is larger.
static LAST_ID: AtomicU64 = AtomicU64::new(0);

/// Identifier of a backup: `b` followed by 16 lowercase hex digits (time and counter).
#[derive(Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct BackupId(pub String);

impl BackupId {
    /// A new id, larger than every id generated by this process or seen by
    /// [`BackupStore::open`]: the time in milliseconds (48 bits) and a counter (16 bits), so ids
    /// sort in creation order.
    pub fn generate() -> Self {
        let now = u64::try_from(system_time_to_millis(SystemTime::now())).unwrap_or(0);
        let base = (now & ((1 << (64 - COUNTER_BITS)) - 1)) << COUNTER_BITS;
        let mut last = LAST_ID.load(Ordering::Relaxed);
        loop {
            let next = base.max(last.wrapping_add(1));
            match LAST_ID.compare_exchange_weak(last, next, Ordering::Relaxed, Ordering::Relaxed) {
                Ok(_) => return Self(format!("b{next:016x}")),
                Err(current) => last = current,
            }
        }
    }

    /// The id written as `text`, when it is well formed (`b` and 16 lowercase hex digits).
    pub fn parse(text: &str) -> Option<Self> {
        let digits = text.strip_prefix('b')?;
        (digits.len() == ID_DIGITS
            && digits
                .bytes()
                .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte)))
        .then(|| Self(text.to_owned()))
    }

    /// Whether the id is well formed (`b` and 16 lowercase hex digits).
    pub fn is_well_formed(&self) -> bool {
        Self::parse(&self.0).is_some()
    }

    /// The 64-bit value of a well-formed id.
    fn value(&self) -> Option<u64> {
        self.is_well_formed()
            .then(|| u64::from_str_radix(&self.0[1..], 16).ok())
            .flatten()
    }

    /// Makes every id generated from now on larger than this one.
    fn observe(&self) {
        if let Some(value) = self.value() {
            LAST_ID.fetch_max(value, Ordering::Relaxed);
        }
    }
}

/// One entry of `backups/index.toml`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct BackupEntry {
    /// The backup.
    pub id: BackupId,
    /// The file the buffer belongs to; `None` for an untitled buffer.
    pub file: Option<PathBuf>,
    /// The title of an untitled buffer.
    pub title: Option<String>,
    /// Id of the buffer's original encoding (the backup text is always UTF-8).
    pub encoding: String,
    /// The file's stamp at load or last save; `None` for an untitled buffer.
    pub disk: Option<DiskStamp>,
    /// When the backup was last written (UTC).
    pub updated_utc: String,
}

/// The backup folder and its index.
#[derive(Debug)]
pub struct BackupStore {
    /// The folders, to re-create `backups/` before a write if it was deleted meanwhile.
    paths: Paths,
    /// The `backups` folder.
    dir: PathBuf,
    /// The entries of the index.
    entries: Vec<BackupEntry>,
    /// Text files with no index entry, as found by [`BackupStore::open`] and not yet adopted
    /// or removed.
    orphans: Vec<BackupId>,
    /// The index has a newer `schema_version`: nothing is written for this session.
    disabled: bool,
}

/// A buffer to restore after a restart.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum RestoreItem {
    /// A backup listed in the index.
    Entry {
        /// Its index entry.
        entry: BackupEntry,
        /// The backed-up text.
        text: String,
    },
    /// A backup text with no index entry (left by a kill between the two writes).
    Orphan {
        /// Its id, from the file name.
        id: BackupId,
        /// The backed-up text.
        text: String,
    },
}

impl RestoreItem {
    /// The backup id of the item.
    fn id(&self) -> &BackupId {
        match self {
            Self::Entry { entry, .. } => &entry.id,
            Self::Orphan { id, .. } => id,
        }
    }

    /// Whether the session tab `source` names this item: a file tab its entry's file, a backup
    /// tab its id.
    fn is_named_by(&self, source: &TabSource) -> bool {
        match (source, self) {
            (TabSource::File(path), Self::Entry { entry, .. }) => {
                entry.file.as_deref() == Some(path.as_path())
            }
            (TabSource::File(_), Self::Orphan { .. }) => false,
            (TabSource::Backup(id), item) => item.id() == id,
        }
    }
}

impl BackupStore {
    /// Opens the backup folder of `paths` and returns what to restore, with the problems found.
    ///
    /// The folder is created first if missing ([`Paths::create_backups_dir`], `0o700` on
    /// Unix). The items are the index entries in index order, then the orphans (`<id>.txt`
    /// files with no entry) in id order, which is creation order; only regular files named
    /// `b<16 hex>.txt` are read, never a `*.tmp` file. An entry whose text is missing is
    /// reported and dropped from the index at its next write; a text that cannot be read (too
    /// large, not UTF-8, I/O error) is reported, not restored, and kept. An index that is not
    /// valid TOML is reported and its texts come back as orphans. An index with a newer
    /// `schema_version` gives [`BackupProblem::NewerSchema`], no item, and a disabled store.
    ///
    /// # Errors
    /// The folder or the index cannot be read.
    pub fn open(paths: &Paths) -> std::io::Result<(Self, Vec<RestoreItem>, Vec<BackupProblem>)> {
        paths.create_backups_dir()?;
        let dir = paths.backups_dir();
        let mut problems = Vec::new();
        let listed = match read_limited(&paths.backups_index(), MAX_INDEX_BYTES) {
            Ok(bytes) => match String::from_utf8(bytes) {
                Ok(text) => parse_index(&text, &mut problems),
                Err(error) => {
                    problems.push(BackupProblem::Unreadable(format!(
                        "backups/index.toml is not UTF-8 (byte {})",
                        error.utf8_error().valid_up_to()
                    )));
                    Some(Vec::new())
                }
            },
            Err(error) if error.kind() == io::ErrorKind::NotFound => Some(Vec::new()),
            Err(error) => return Err(error),
        };
        let texts = list_texts(&dir)?;
        texts.iter().for_each(BackupId::observe);

        let mut store = Self {
            paths: paths.clone(),
            dir,
            entries: Vec::new(),
            orphans: Vec::new(),
            disabled: false,
        };
        let Some(listed) = listed else {
            store.disabled = true;
            problems.push(BackupProblem::NewerSchema);
            return Ok((store, Vec::new(), problems));
        };

        let mut items = Vec::new();
        for entry in listed {
            entry.id.observe();
            if !texts.contains(&entry.id) {
                problems.push(BackupProblem::MissingText(entry.id));
                continue;
            }
            match store.read_text(&entry.id) {
                Ok(text) => items.push(RestoreItem::Entry {
                    entry: entry.clone(),
                    text,
                }),
                Err(detail) => problems.push(BackupProblem::Unreadable(detail)),
            }
            store.entries.push(entry);
        }
        for id in texts {
            if store.entries.iter().any(|entry| entry.id == id) {
                continue;
            }
            match store.read_text(&id) {
                Ok(text) => items.push(RestoreItem::Orphan {
                    id: id.clone(),
                    text,
                }),
                Err(detail) => problems.push(BackupProblem::Unreadable(detail)),
            }
            store.orphans.push(id);
        }
        Ok((store, items, problems))
    }

    /// Writes `<id>.txt` atomically, then the index.
    ///
    /// An entry with the id of an existing one replaces it in place (index order is kept); the
    /// id of an orphan adopts it. The `backups` folder is re-created first if it was deleted.
    ///
    /// # Errors
    /// Any I/O error of the two atomic writes (the index is not written when the text write
    /// fails); `InvalidInput` for an id that is not well formed; `Unsupported` when the store
    /// is disabled by a newer index schema.
    pub fn write(&mut self, entry: BackupEntry, text: WriteFn) -> std::io::Result<()> {
        self.check_writable(&entry.id)?;
        write_atomic(&self.text_path(&entry.id), text)?;
        entry.id.observe();
        self.orphans.retain(|id| *id != entry.id);
        match self.entries.iter_mut().find(|known| known.id == entry.id) {
            Some(known) => *known = entry,
            None => self.entries.push(entry),
        }
        self.write_index()
    }

    /// Removes `id` from the index first, then its text file.
    ///
    /// An orphan's text file is removed too; a text file that is already gone is not an error.
    /// When the index write fails, the entry stays (in memory and on disk) and its text is kept.
    ///
    /// # Errors
    /// Any I/O error of the index write or the removal; `InvalidInput` for an id that is not
    /// well formed; `Unsupported` when the store is disabled by a newer index schema.
    pub fn remove(&mut self, id: &BackupId) -> std::io::Result<()> {
        self.check_writable(id)?;
        if let Some(position) = self.entries.iter().position(|entry| entry.id == *id) {
            let entry = self.entries.remove(position);
            if let Err(error) = self.write_index() {
                self.entries.insert(position, entry);
                return Err(error);
            }
        }
        match fs::remove_file(self.text_path(id)) {
            Ok(()) => {
                self.orphans.retain(|orphan| orphan != id);
                Ok(())
            }
            Err(error) if error.kind() == io::ErrorKind::NotFound => {
                self.orphans.retain(|orphan| orphan != id);
                Ok(())
            }
            Err(error) => {
                // The text outlives its entry: it is an orphan now, adopted at the next open.
                if !self.orphans.contains(id) {
                    self.orphans.push(id.clone());
                }
                Err(error)
            }
        }
    }

    /// The entries of the index, in index order.
    pub fn entries(&self) -> &[BackupEntry] {
        &self.entries
    }

    /// Whether the store is disabled (the index has a newer `schema_version`): nothing is
    /// written for this session.
    pub fn is_disabled(&self) -> bool {
        self.disabled
    }

    /// Refuses writes of a disabled store and ids that are not well formed (which could name
    /// a file outside the folder), then makes sure the folder exists.
    fn check_writable(&self, id: &BackupId) -> io::Result<()> {
        if self.disabled {
            return Err(io::Error::new(
                io::ErrorKind::Unsupported,
                "backups are disabled: backups/index.toml has a newer schema_version",
            ));
        }
        if !id.is_well_formed() {
            return Err(io::Error::new(
                io::ErrorKind::InvalidInput,
                "a backup id is `b` followed by 16 lowercase hex digits",
            ));
        }
        self.paths.create_backups_dir()
    }

    /// `<backups>/<id>.txt`.
    fn text_path(&self, id: &BackupId) -> PathBuf {
        self.dir.join(format!("{}{TEXT_EXTENSION}", id.0))
    }

    /// The text of `id`, or an English detail of why it cannot be read.
    fn read_text(&self, id: &BackupId) -> Result<String, String> {
        let name = format!("backups/{}{TEXT_EXTENSION}", id.0);
        let bytes = read_limited(&self.text_path(id), MAX_TEXT_BYTES)
            .map_err(|error| format!("{name} cannot be read: {}", error.kind()))?;
        String::from_utf8(bytes).map_err(|error| {
            format!(
                "{name} is not UTF-8 (byte {})",
                error.utf8_error().valid_up_to()
            )
        })
    }

    /// Writes the index atomically from the entries.
    fn write_index(&self) -> io::Result<()> {
        let text = index_to_toml(&self.entries);
        write_atomic(
            &self.paths.backups_index(),
            Box::new(move |out| out.write_all(text.as_bytes())),
        )
    }
}

/// A problem found by [`BackupStore::open`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum BackupProblem {
    /// The index lists a backup whose text file is missing.
    MissingText(BackupId),
    /// The index has a newer `schema_version`: backups are disabled for this session.
    NewerSchema,
    /// The index or a text file cannot be read; the detail is English.
    Unreadable(String),
}

/// Orders the items of [`BackupStore::open`] for the restore of m4 §4.8: by the first tab of
/// `session` that names each one (a `TabSource::File` tab the entry whose `file` is its path,
/// a `TabSource::Backup` tab the entry or orphan of its id), then the items no tab names, in
/// their order (entries, then orphans). The sort is stable.
pub fn restore_order(mut items: Vec<RestoreItem>, session: &Session) -> Vec<RestoreItem> {
    items.sort_by_key(|item| {
        session
            .tabs
            .iter()
            .position(|tab| item.is_named_by(&tab.source))
            .unwrap_or(usize::MAX)
    });
    items
}

/// `time` as an RFC 3339 UTC timestamp to the second (`2026-11-04T09:30:00Z`), the format of
/// `BackupEntry::updated_utc`.
pub fn utc_timestamp(time: SystemTime) -> String {
    let seconds = system_time_to_millis(time).div_euclid(1000);
    let (days, of_day) = (seconds.div_euclid(86_400), seconds.rem_euclid(86_400));
    let (year, month, day) = civil_from_days(days);
    format!(
        "{year:04}-{month:02}-{day:02}T{:02}:{:02}:{:02}Z",
        of_day / 3600,
        of_day % 3600 / 60,
        of_day % 60
    )
}

/// The proleptic Gregorian date of `days` since 1970-01-01 (H. Hinnant's `civil_from_days`).
fn civil_from_days(days: i64) -> (i64, i64, i64) {
    let shifted = days + 719_468;
    let era = shifted.div_euclid(146_097);
    let day_of_era = shifted.rem_euclid(146_097);
    let year_of_era =
        (day_of_era - day_of_era / 1460 + day_of_era / 36_524 - day_of_era / 146_096) / 365;
    let day_of_year = day_of_era - (365 * year_of_era + year_of_era / 4 - year_of_era / 100);
    let shifted_month = (5 * day_of_year + 2) / 153;
    let day = day_of_year - (153 * shifted_month + 2) / 5 + 1;
    let month = if shifted_month < 10 {
        shifted_month + 3
    } else {
        shifted_month - 9
    };
    let year = year_of_era + era * 400 + i64::from(month <= 2);
    (year, month, day)
}

/// The ids of the regular files `b<16 hex>.txt` of `dir`, in id order.
fn list_texts(dir: &Path) -> io::Result<BTreeSet<BackupId>> {
    let mut texts = BTreeSet::new();
    for item in fs::read_dir(dir)? {
        let item = item?;
        let name = item.file_name();
        let Some(id) = name
            .to_str()
            .and_then(|name| name.strip_suffix(TEXT_EXTENSION))
            .and_then(BackupId::parse)
        else {
            continue;
        };
        if item.file_type()?.is_file() {
            texts.insert(id);
        }
    }
    Ok(texts)
}

/// The entries of an index text; `None` when its `schema_version` is newer. Damage (a syntax
/// error, a bad `schema_version`, an entry without a valid id) is reported as
/// [`BackupProblem::Unreadable`] and the damaged part is skipped.
fn parse_index(text: &str, problems: &mut Vec<BackupProblem>) -> Option<Vec<BackupEntry>> {
    let text = text.strip_prefix('\u{feff}').unwrap_or(text);
    let document = match text.parse::<Table>() {
        Ok(document) => document,
        Err(error) => {
            problems.push(BackupProblem::Unreadable(format!(
                "backups/index.toml is not valid TOML: {}",
                error.message()
            )));
            return Some(Vec::new());
        }
    };
    match document.get("schema_version") {
        None => {}
        Some(Value::Integer(version)) if *version == SCHEMA_VERSION => {}
        Some(Value::Integer(version)) if *version > SCHEMA_VERSION => return None,
        Some(_) => {
            problems.push(BackupProblem::Unreadable(
                "backups/index.toml has an invalid schema_version".to_owned(),
            ));
            return Some(Vec::new());
        }
    }
    let tables = match document.get("backup") {
        None => return Some(Vec::new()),
        Some(Value::Array(tables)) => tables,
        Some(_) => {
            problems.push(BackupProblem::Unreadable(
                "backups/index.toml: `backup` is not an array of tables".to_owned(),
            ));
            return Some(Vec::new());
        }
    };
    let mut entries: Vec<BackupEntry> = Vec::new();
    for (position, value) in tables.iter().enumerate() {
        let number = position + 1;
        let entry = match value {
            Value::Table(table) => parse_entry(table),
            _ => None,
        };
        let Some(entry) = entry else {
            problems.push(BackupProblem::Unreadable(format!(
                "backups/index.toml: backup entry {number} has no valid id"
            )));
            continue;
        };
        if entries.iter().any(|known| known.id == entry.id) {
            problems.push(BackupProblem::Unreadable(format!(
                "backups/index.toml: backup entry {number} repeats the id {}",
                entry.id.0
            )));
            continue;
        }
        entries.push(entry);
    }
    Some(entries)
}

/// One `[[backup]]` table, or `None` without a well-formed `id`. The other fields are optional:
/// a missing or wrong-typed one is absent (`encoding` then `utf-8`, `updated_utc` empty).
fn parse_entry(table: &Table) -> Option<BackupEntry> {
    let text = |key: &str| match table.get(key) {
        Some(Value::String(text)) => Some(text.clone()),
        _ => None,
    };
    let integer = |key: &str| match table.get(key) {
        Some(Value::Integer(number)) => Some(*number),
        _ => None,
    };
    let id = BackupId::parse(&text("id")?)?;
    let disk = integer("disk_len")
        .and_then(|len| u64::try_from(len).ok())
        .map(|len| DiskStamp {
            len,
            modified: integer("disk_modified_ms").and_then(millis_to_system_time),
        });
    Some(BackupEntry {
        id,
        file: text("file").map(PathBuf::from),
        title: text("title"),
        encoding: text("encoding").unwrap_or_else(|| DEFAULT_ENCODING.to_owned()),
        disk,
        updated_utc: text("updated_utc").unwrap_or_default(),
    })
}

/// The index text: `schema_version = 1`, then one `[[backup]]` table per entry with the
/// `BackupEntry` fields (`disk` as `disk_len` and `disk_modified_ms`; absent keys for `None`).
///
/// A `file` that is not valid Unicode cannot be stored: the entry is then written as an
/// untitled buffer (no `file`, no disk stamp) titled with the lossy path, so its text is still
/// restored.
fn index_to_toml(entries: &[BackupEntry]) -> String {
    let mut out = format!("schema_version = {SCHEMA_VERSION}\n");
    for entry in entries {
        let _ = write!(out, "\n[[backup]]\nid = {}\n", toml_string(&entry.id.0));
        let (file, title) = match entry.file.as_deref() {
            Some(path) => match path.to_str() {
                Some(path) => (Some(path), entry.title.clone()),
                None => (
                    None,
                    Some(
                        entry
                            .title
                            .clone()
                            .unwrap_or_else(|| path.to_string_lossy().into_owned()),
                    ),
                ),
            },
            None => (None, entry.title.clone()),
        };
        if let Some(file) = file {
            let _ = writeln!(out, "file = {}", toml_string(file));
        }
        if let Some(title) = title {
            let _ = writeln!(out, "title = {}", toml_string(&title));
        }
        let _ = writeln!(out, "encoding = {}", toml_string(&entry.encoding));
        if let (Some(_), Some(disk)) = (file, entry.disk) {
            let len = i64::try_from(disk.len).unwrap_or(i64::MAX);
            let _ = writeln!(out, "disk_len = {len}");
            if let Some(modified) = disk.modified {
                let _ = writeln!(
                    out,
                    "disk_modified_ms = {}",
                    system_time_to_millis(modified)
                );
            }
        }
        let _ = writeln!(out, "updated_utc = {}", toml_string(&entry.updated_utc));
    }
    out
}
